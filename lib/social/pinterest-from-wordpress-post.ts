/**
 * Pinterest from an existing WordPress post (Volet A): a post that already
 * lives on a connected site, never generated by OmniFlow. It becomes the
 * same ArticlePinterestSource / WordPressArticleContext as an OmniFlow
 * article, so the whole Pinterest pipeline is shared. Read-only: one GET to
 * WordPress, select-only Supabase calls; the post is never modified. Its
 * verified permalink is the Pins' default destination URL (TASK-071) and
 * never reaches the prompt.
 */

/**
 * The post's own `link`, kept as is, only when WordPress says it is
 * published and the link points into the connected site (same rule as the
 * Medium CTA). Never rebuilt from a slug, never guessed.
 */
export function verifiedPostPermalink(link: string | null | undefined, siteUrl: string, postStatus: string): string | null {
  if (!link || postStatus !== 'publish') return null;
  return toAllowedInternalUrl(link, siteUrl);
}

/**
 * generations columns of migration 044 for a Pinterest generation made from
 * an article. `source_wordpress_generation_id` (migration 040) keeps its own
 * meaning — OmniFlow articles only — and is written separately.
 */
export function generationSourceColumns(source: Pick<ArticlePinterestSource, 'sourceType' | 'externalPost'>): {
  source_type: 'omniflow_article' | 'external_wordpress_post';
  source_wordpress_site_id: string | null;
  source_wordpress_post_id: number | null;
} {
  return {
    source_type: source.sourceType,
    source_wordpress_site_id: source.externalPost?.siteId ?? null,
    source_wordpress_post_id: source.externalPost?.postId ?? null,
  };
}

export interface OwnedWordPressSite {
  site: WordPressSite;
  credentials: WordPressSiteCredentials;
}

/** The connection, if it exists and belongs to the user. Decrypts the password server-side only. */
export async function loadOwnedWordPressSite(supabase: SupabaseClient, userId: string, siteId: string): Promise<OwnedWordPressSite> {
  const { data } = await supabase.from('wordpress_sites').select('*').eq('id', siteId).single();
  const site = data as WordPressSite | null;
  if (!site) throw new SocialGenerationError('not_found', 'WordPress connection not found');
  if (site.user_id !== userId) throw new SocialGenerationError('forbidden', 'You do not have access to this WordPress connection');

  let password: string;
  try {
    password = decryptSecret(site.encrypted_application_password);
  } catch {
    throw new SocialGenerationError('generation_failed', 'The saved WordPress credentials could not be read. Reconnect the site.');
  }
  return { site, credentials: { siteUrl: site.site_url, username: site.wp_username, password } };
}

function toLanguage(value: string | null | undefined): SupportedLanguage {
  return (SUPPORTED_LANGUAGES as readonly string[]).includes(value ?? '') ? (value as SupportedLanguage) : 'en';
}

export interface WordPressPostPinterestSource extends ArticlePinterestSource {
  post: Pick<WordPressPostDetail, 'id' | 'date' | 'status' | 'categories'>;
}

/** Pure: a fetched post + its project → the shared Pinterest source. */
export function buildWordPressPostPinterestSource(
  post: WordPressPostDetail,
  site: Pick<WordPressSite, 'id' | 'project_id' | 'site_url'>,
  project: { niche: string | null; description: string | null; default_language: string | null }
): WordPressPostPinterestSource {
  const language = toLanguage(project.default_language);
  const context = buildWordPressArticleContext({
    sourceType: 'external_wordpress_post',
    html: post.contentHtml,
    title: post.title,
    excerpt: post.excerpt,
    language,
    siteId: site.id,
    wordpressPostId: post.id,
    featuredImage: post.featuredImage,
    categories: post.categories,
    tags: post.tags,
    permalink: post.link || null,
  });

  return {
    articleId: null,
    sourceType: 'external_wordpress_post',
    externalPost: { siteId: site.id, postId: post.id },
    projectId: site.project_id,
    title: context.title,
    metaTitle: context.title,
    metaDescription: context.excerpt,
    content: context.plainText,
    primaryKeyword: null,
    seoKeywords: context.tags.slice(0, 10),
    language,
    featuredImageUrl: post.featuredImage?.url ?? null,
    featuredImagePrompt: post.featuredImage?.alt || null,
    niche: project.niche,
    contentStreams: [],
    nicheSettings: null,
    brandProfileDescription: project.description,
    context,
    siteUrl: site.site_url,
    permalink: verifiedPostPermalink(post.link, site.site_url, post.status),
    post: { id: post.id, date: post.date, status: post.status, categories: post.categories },
  };
}

/**
 * Ownership of the connection and of its project, then one GET of the post.
 * WordPress failures surface as WordPressReadError (401/403/404/timeout/empty).
 */
export async function loadWordPressPostPinterestSource(
  supabase: SupabaseClient,
  userId: string,
  source: WordPressPostSource,
  deps: ReadDeps = {}
): Promise<WordPressPostPinterestSource> {
  const { site, credentials } = await loadOwnedWordPressSite(supabase, userId, source.siteId);

  const { data: project } = await supabase
    .from('projects')
    .select('id, user_id, niche, description, default_language')
    .eq('id', site.project_id)
    .single();
  if (!project) throw new SocialGenerationError('not_found', 'Project not found');
  if (project.user_id !== userId) throw new SocialGenerationError('forbidden', 'You do not have access to this project');

  const post = await getWordPressPost(credentials, source.postId, deps);
  const built = buildWordPressPostPinterestSource(post, site, {
    niche: (project.niche as string | null) ?? null,
    description: (project.description as string | null) ?? null,
    default_language: (project.default_language as string | null) ?? null,
  });
  return {
    ...built,
    contentStreams: await contentStreamsForPostCategories(supabase, userId, site.project_id, post.categoryIds),
    nicheSettings: await getProjectNicheSettings(supabase, userId, site.project_id),
  };
}

/**
 * Content Streams of the post's WordPress categories, through the project's
 * mapped OmniFlow categories (wordpress_categories.wp_category_id).
 * Best-effort: unmapped categories or a query error give no stream.
 */
async function contentStreamsForPostCategories(
  supabase: SupabaseClient,
  userId: string,
  projectId: string,
  wpCategoryIds: number[]
): Promise<string[]> {
  if (wpCategoryIds.length === 0) return [];
  const { data, error } = await supabase
    .from('wordpress_categories')
    .select('id')
    .eq('project_id', projectId)
    .in('wp_category_id', wpCategoryIds);
  if (error || !data) return [];
  const names = await Promise.all(
    (data as Array<{ id: string }>).map((category) => listContentStreamNamesForCategory(supabase, userId, projectId, category.id))
  );
  return [...new Set(names.flat())];
}
