-- ============================================
-- OmniFlow Migration 044
-- Pinterest from an existing WordPress post (Volet A) + source kind
-- ============================================

-- What a Pinterest generation was made from, when it was made from an article:
--   source_type = 'omniflow_article'         → an article written by the
--                 WordPress generator; source_wordpress_generation_id
--                 (migration 040) keeps pointing at it, unchanged.
--   source_type = 'external_wordpress_post'  → a post that already existed on
--                 a connected WordPress site (never generated by OmniFlow),
--                 identified by source_wordpress_site_id + source_wordpress_post_id
--                 (the WordPress post id on that site).
--   source_type NULL                         → keyword generation, and every
--                 row written before this migration.
-- Traceability only: ids, never a URL. The post permalink is not stored and
-- pins.link_url stays empty (destinations are added manually in the CSV).
-- Written best-effort after the generation completes, so generating still
-- works before this migration is applied.
-- Additive only: no backfill, no change to existing rows, no RLS change (the
-- existing "Users access own generations" policy already covers the row).
ALTER TABLE generations
  ADD COLUMN source_type text
    CHECK (source_type IN ('omniflow_article', 'external_wordpress_post')),
  ADD COLUMN source_wordpress_site_id uuid
    REFERENCES wordpress_sites(id) ON DELETE SET NULL,
  ADD COLUMN source_wordpress_post_id bigint
    CHECK (source_wordpress_post_id > 0);

-- A WordPress post reference only ever belongs to an external-post source.
-- (The site id alone may become NULL when the connection is deleted.)
ALTER TABLE generations
  ADD CONSTRAINT generations_source_wordpress_post_kind
  CHECK (source_wordpress_post_id IS NULL OR source_type = 'external_wordpress_post');

CREATE INDEX idx_generations_source_wordpress_post
  ON generations(source_wordpress_site_id, source_wordpress_post_id)
  WHERE source_wordpress_post_id IS NOT NULL;
